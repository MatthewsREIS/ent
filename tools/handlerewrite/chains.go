// -chains mode: a types-aware rewriter that decomposes old generated
// setter-chain calls (Set<F>, Add<F>, Set<E>ID, ...) on entc Create/Update
// builders into the F/E handle assignment form, folding consecutive
// rewritten calls into one .With(...). Unlike v1 (syntax mode), receiver
// types are resolved via go/packages type-checking, so there is no
// identifier-shadowing heuristic to get conservative about: a call only
// rewrites when its receiver's *static type* is a manifest-tracked builder,
// regardless of what any local variable happens to be named.
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/token"
	"go/types"
	"os"
	"path"
	"strconv"
	"strings"

	"golang.org/x/tools/go/ast/astutil"
	"golang.org/x/tools/go/packages"
)

// setterReading is one decomposition of a builder method name against a
// manifest entity's setters table: "call <Handle>.<Name>.<Op>(args...)".
type setterReading struct {
	handle string // "Field" or "Edge"
	name   string // the field/edge's PascalCase name
	op     string // the handle method to call: Set, SetNillable, Add, ...
}

func (r setterReading) String() string { return r.handle + "." + r.name + "." + r.op }

// decomposeSetter returns every valid reading of method against setters.
// Rather than stripping a fixed prefix/suffix off method and looking the
// remainder up by map key (which can't work for Add<E>IDs/Remove<E>IDs —
// see below), it does the inverse: for each entry, generate the exact
// method name real entc codegen would have produced for each op that
// entry supports, and keep the ones that equal method. Given the setters
// map is keyed uniquely per field/edge name, most method names match at
// most one entry; two matches are possible when two different keys'
// generated names collide (e.g. "SetStatusID" is generated by a field
// "StatusID"'s Set form AND by a unique edge "Status"'s SetID form) —
// genuinely ambiguous, and the caller must refuse to guess.
//
// Naming rules below are verified against entc/gen (not guessed): see
// Edge.MutationSet/MutationAdd/MutationRemove/MutationClear in
// entc/gen/type.go, and entc/gen/template/builder/{setter,update}.tmpl.
//   - Set<StructField>ID / SetNillable<StructField>ID (unique edge): the
//     edge's StructField used as-is — never singularized.
//   - Add<X>IDs / Remove<X>IDs (non-unique edge): X is the *singularized*
//     edge name (e.g. edge "Parcels" -> "AddParcelIDs"), which the
//     manifest carries explicitly as SetterEntry.MethodBase since
//     singularization isn't reliably invertible from the method name
//     alone. Falls back to the StructField itself when MethodBase is
//     empty (manifest not yet carrying it, or a hand-written test
//     fixture where the two happen to coincide).
//   - Clear<StructField> (any edge): StructField as-is, never
//     singularized — same field used for both Add/Remove's unique-Set
//     sibling and the plain Clear form.
func decomposeSetter(method string, setters map[string]SetterEntry) []setterReading {
	var cands []setterReading
	for name, e := range setters {
		switch e.Kind {
		case "field", "edgefield":
			switch {
			case method == "Set"+name:
				cands = append(cands, setterReading{"Field", name, "Set"})
			case e.Nillable && method == "SetNillable"+name:
				cands = append(cands, setterReading{"Field", name, "SetNillable"})
			case e.Kind == "field" && e.CanAdd && method == "Add"+name:
				cands = append(cands, setterReading{"Field", name, "Add"})
			case e.Kind == "field" && e.CanAppend && method == "Append"+name:
				cands = append(cands, setterReading{"Field", name, "Append"})
			case method == "Clear"+name:
				cands = append(cands, setterReading{"Field", name, "Clear"})
			}
		case "edge":
			if e.Unique {
				switch {
				case method == "Set"+name+"ID":
					cands = append(cands, setterReading{"Edge", name, "SetID"})
				case e.Nillable && method == "SetNillable"+name+"ID":
					cands = append(cands, setterReading{"Edge", name, "SetNillableID"})
				}
			} else {
				base := e.MethodBase
				if base == "" {
					base = name // fixture-simplicity fallback; real manifests set this.
				}
				switch {
				case method == "Add"+base+"IDs":
					cands = append(cands, setterReading{"Edge", name, "AddIDs"})
				case method == "Remove"+base+"IDs":
					cands = append(cands, setterReading{"Edge", name, "RemoveIDs"})
				}
			}
			if method == "Clear"+name {
				cands = append(cands, setterReading{"Edge", name, "Clear"})
			}
		}
	}
	return cands
}

// splitBuilderType reports whether name is a generated builder type name
// (<Entity>Create, <Entity>Update, or <Entity>UpdateOne) and, if so, the
// entity name. "UpdateOne" is checked before "Update" (longer suffix
// first), since every "UpdateOne" name also ends in "One" but NOT in the
// bare "Update" suffix's usual sense — checked explicitly to avoid ever
// trimming "UpdateOne" down to "...UpdateOne" minus "Update" = "...One".
func splitBuilderType(name string) (entity string, ok bool) {
	switch {
	case strings.HasSuffix(name, "UpdateOne"):
		return strings.TrimSuffix(name, "UpdateOne"), true
	case strings.HasSuffix(name, "Update"):
		return strings.TrimSuffix(name, "Update"), true
	case strings.HasSuffix(name, "Create"):
		return strings.TrimSuffix(name, "Create"), true
	}
	return "", false
}

// namedType unwraps a (possibly pointer) type down to its *types.Named, or
// nil if t isn't a (pointer to a) named type.
func namedType(t types.Type) *types.Named {
	if t == nil {
		return nil
	}
	if p, ok := t.(*types.Pointer); ok {
		t = p.Elem()
	}
	n, _ := t.(*types.Named)
	return n
}

// rewriteCtx holds the per-file state for one -chains rewrite pass: the
// type info to resolve receivers against, the manifest and pkgprefix guard,
// and a cache of import aliases already resolved/added in this file.
type rewriteCtx struct {
	fset      *token.FileSet
	info      *types.Info
	manifest  Manifest
	prefixes  []string
	file      *ast.File
	filename  string
	aliases   map[string]string // importPath -> local alias, resolved lazily
	changed   bool
	ambiguous bool
}

func (rc *rewriteCtx) typeOf(e ast.Expr) types.Type {
	if tv, ok := rc.info.Types[e]; ok {
		return tv.Type
	}
	return nil
}

// builderEntry reports the manifest entry for t, if t is a (pointer to a)
// generated builder type (<Entity>Create/Update/UpdateOne) whose package
// path passes the -pkgprefix guard and whose entity has a manifest entry
// with a non-nil setters table.
func (rc *rewriteCtx) builderEntry(t types.Type) (PkgEntry, bool) {
	named := namedType(t)
	if named == nil {
		return PkgEntry{}, false
	}
	obj := named.Obj()
	if obj.Pkg() == nil {
		return PkgEntry{}, false
	}
	if len(rc.prefixes) > 0 && !hasAnyPrefix(obj.Pkg().Path(), rc.prefixes) {
		return PkgEntry{}, false
	}
	entity, ok := splitBuilderType(obj.Name())
	if !ok {
		return PkgEntry{}, false
	}
	entry, ok := rc.manifest[strings.ToLower(entity)]
	if !ok || entry.Setters == nil {
		return PkgEntry{}, false
	}
	return entry, true
}

// ensureImport returns the local identifier this file uses to refer to
// importPath, adding the import (unaliased) if the file doesn't have it
// yet. An existing import's alias (explicit or, absent one, the import's
// base package name) is reused rather than duplicated.
func (rc *rewriteCtx) ensureImport(importPath string) string {
	if alias, ok := rc.aliases[importPath]; ok {
		return alias
	}
	for _, imp := range rc.file.Imports {
		p, err := strconv.Unquote(imp.Path.Value)
		if err != nil || p != importPath {
			continue
		}
		alias := path.Base(p)
		if imp.Name != nil {
			alias = imp.Name.Name
		}
		rc.aliases[importPath] = alias
		return alias
	}
	astutil.AddImport(rc.fset, rc.file, importPath)
	alias := path.Base(importPath)
	rc.aliases[importPath] = alias
	return alias
}

func (rc *rewriteCtx) warnAmbiguous(sel *ast.SelectorExpr, cands []setterReading) {
	pos := rc.fset.Position(sel.Pos())
	names := make([]string, len(cands))
	for i, c := range cands {
		names[i] = c.String()
	}
	fmt.Fprintf(os.Stderr, "handlerewrite: %s:%d: ambiguous chain rewrite for .%s(...) — competing readings: %s — refusing to rewrite\n",
		pos.Filename, pos.Line, sel.Sel.Name, strings.Join(names, ", "))
	rc.ambiguous = true
}

// exprResult is the outcome of processExpr on one expression.
type exprResult struct {
	expr ast.Expr
	// changed reports whether anything under expr (including expr itself)
	// was rewritten.
	changed bool
	// openWith, if non-nil, is expr's own *ast.CallExpr — a synthesized
	// `.With(...)` call that a caller decomposing the *next* link in the
	// same chain may extend in place (fold) rather than wrap in a new
	// `.With(...)`. nil means the chain is "closed" here: expr's outermost
	// call was left as an ordinary call (not a decomposed setter), so the
	// next link (if any) must start a fresh `.With(...)`.
	openWith *ast.CallExpr
	// entry/hasEntry carry the manifest entry for expr's builder type, once
	// known, so the *next* link in the same chain can decompose even when
	// its own receiver's static type fails to resolve. That happens for
	// every setter chain this tool is meant to migrate: once the first
	// old Set<F> in a chain is gone from the generated builder, go/types
	// can no longer type the *next* link's original receiver expression
	// (`recv.SetFoo(...)`) at all — it was built on a call to a method
	// that no longer exists — even though the chain's builder type never
	// actually changes link to link. Propagating the entry sidesteps
	// re-deriving it from a static type that's gone missing precisely
	// because a sibling link in the same chain was already rewritten.
	entry    PkgEntry
	hasEntry bool
}

// buildHandleCall renders `<pkgAlias>.<r.handle>.<r.name>.<r.op>(args...)`.
// ellipsis is the original call's Ellipsis position (call.Ellipsis) — a
// non-zero value marks the last arg as a `slice...` spread (e.g.
// AddUserIDs(ids...)); it must carry over verbatim or the rewritten call
// silently drops the spread and fails to compile against the handle's
// variadic parameter.
func buildHandleCall(pkgAlias string, r setterReading, args []ast.Expr, ellipsis token.Pos) *ast.CallExpr {
	sel := &ast.SelectorExpr{
		X: &ast.SelectorExpr{
			X:   &ast.SelectorExpr{X: ast.NewIdent(pkgAlias), Sel: ast.NewIdent(r.handle)},
			Sel: ast.NewIdent(r.name),
		},
		Sel: ast.NewIdent(r.op),
	}
	return &ast.CallExpr{Fun: sel, Args: args, Ellipsis: ellipsis}
}

// processExpr recursively rewrites e (bottom-up: receivers and arguments
// before the call itself), folding consecutive decomposed setter calls in
// one method chain into a single `.With(...)`.
func (rc *rewriteCtx) processExpr(e ast.Expr) exprResult {
	call, ok := e.(*ast.CallExpr)
	if !ok {
		// Not a call at all — but it may still CONTAIN calls arbitrarily
		// deep inside (most commonly a func literal argument, e.g.
		// t.Run(name, func(t *testing.T) { ...chain... })). The receiver/
		// args recursion above only walks direct call-expression positions;
		// it can't see into a func literal's body on its own. Fall back to
		// a full sub-tree walk so setter chains nested in there still get
		// rewritten.
		return exprResult{expr: e, changed: rc.walkForChains(e)}
	}
	sel, ok := call.Fun.(*ast.SelectorExpr)
	if !ok {
		// Not a method call (e.g. a plain function call) — still walk args
		// for nested chains, e.g. Must(client.X.Create().SetName(v)...).
		changed := false
		for i, a := range call.Args {
			r := rc.processExpr(a)
			if r.changed {
				call.Args[i] = r.expr
				changed = true
			}
		}
		return exprResult{expr: call, changed: changed}
	}

	origRecv := sel.X
	recvType := rc.typeOf(origRecv)
	recvRes := rc.processExpr(origRecv)
	sel.X = recvRes.expr

	argsChanged := false
	for i, a := range call.Args {
		r := rc.processExpr(a)
		if r.changed {
			call.Args[i] = r.expr
			argsChanged = true
		}
	}

	entry, ok := rc.builderEntry(recvType)
	if !ok && recvType == nil && recvRes.hasEntry {
		// recv's original static type is unresolvable — not because it's
		// some unrelated type, but because go/types has nothing at all for
		// it (recvType == nil): the usual case is that recv itself is a
		// call to a Set<F>/Add<F>/... method already deleted from the
		// generated builder by this same migration. The previous link in
		// this chain already resolved (or inherited) the builder's entry;
		// reuse it rather than giving up.
		entry, ok = recvRes.entry, true
	}
	if ok {
		switch cands := decomposeSetter(sel.Sel.Name, entry.Setters); len(cands) {
		case 1:
			alias := rc.ensureImport(entry.ImportPath)
			argExpr := buildHandleCall(alias, cands[0], call.Args, call.Ellipsis)
			if recvRes.openWith != nil {
				recvRes.openWith.Args = append(recvRes.openWith.Args, argExpr)
				return exprResult{expr: recvRes.expr, changed: true, openWith: recvRes.openWith, entry: entry, hasEntry: true}
			}
			withCall := &ast.CallExpr{
				Fun:  &ast.SelectorExpr{X: recvRes.expr, Sel: ast.NewIdent("With")},
				Args: []ast.Expr{argExpr},
			}
			return exprResult{expr: withCall, changed: true, openWith: withCall, entry: entry, hasEntry: true}
		case 0:
			// Not a setter name (Where/Save/Exec/OnConflict/Mutation/...):
			// an ordinary call. Falls through — closes any open fold, but
			// the builder identity (entry) still carries forward below, so
			// a later setter further down the same chain (e.g. after a
			// Where(...)) is still recognized.
		default:
			rc.warnAmbiguous(sel, cands)
			// Refuse to rewrite this call; falls through as ordinary.
		}
	}

	call.Fun = sel
	return exprResult{expr: call, changed: recvRes.changed || argsChanged, entry: entry, hasEntry: ok}
}

// walkForChains rewrites every setter-chain call site reachable from root
// (root included), via astutil.Apply's own generic tree descent — which,
// unlike processExpr's hand-rolled receiver/args recursion, follows into
// every kind of node (func literal bodies, composite literals, statements
// inside them, ...). It's the single traversal RewriteChainsFile uses at
// the file root, and processExpr's non-call fallback re-enters it for any
// sub-tree its own recursion can't see into directly (e.g. a func literal
// argument). Reports whether anything under root was rewritten.
func (rc *rewriteCtx) walkForChains(root ast.Node) bool {
	changed := false
	astutil.Apply(root, func(cur *astutil.Cursor) bool {
		call, ok := cur.Node().(*ast.CallExpr)
		if !ok {
			return true
		}
		res := rc.processExpr(call)
		if res.changed {
			cur.Replace(res.expr)
			changed = true
		}
		return false
	}, nil)
	return changed
}

// RewriteChainsFile rewrites file's setter-chain call sites in place,
// against pkg's type info. It reports whether any rewrite was made.
func RewriteChainsFile(fset *token.FileSet, info *types.Info, file *ast.File, filename string, manifest Manifest, prefixes []string) bool {
	if isGenerated(file) {
		return false
	}
	rc := &rewriteCtx{fset: fset, info: info, manifest: manifest, prefixes: prefixes, file: file, filename: filename, aliases: map[string]string{}}
	rc.changed = rc.walkForChains(file)
	return rc.changed
}

// ProcessPackages loads the Go packages matching patterns (rooted at dir;
// dir == "" means the current working directory) and rewrites every
// non-generated file's setter-chain call sites in place, returning the
// list of files changed. A package that fails to load or type-check is
// reported and skipped (its files left untouched) rather than aborting the
// whole run — consistent with v1's per-file error handling, since a
// migration over many packages shouldn't be all-or-nothing.
func ProcessPackages(dir string, patterns []string, manifest Manifest, prefixes []string) ([]string, error) {
	cfg := &packages.Config{
		Dir: dir,
		Mode: packages.NeedName | packages.NeedFiles | packages.NeedCompiledGoFiles |
			packages.NeedImports | packages.NeedTypes | packages.NeedSyntax | packages.NeedTypesInfo,
		// Tests: true is required for go/packages to load _test.go files at
		// all (as synthetic "[pkg].test"/"[pkg]_test" packages) — without it
		// every old setter-chain call site in a _test.go file is invisible
		// to this tool, silently skipped rather than rewritten.
		Tests: true,
	}
	pkgs, err := packages.Load(cfg, patterns...)
	if err != nil {
		return nil, fmt.Errorf("load packages: %w", err)
	}
	var changedFiles []string
	seen := map[string]bool{}
	for _, pkg := range pkgs {
		if len(pkg.Errors) > 0 {
			// Don't skip the package: this is exactly the expected state for
			// every file this tool needs to touch — a generated builder just
			// dropped the old Set<F>/Add<F>/... methods, so any caller still
			// using them fails to type-check by definition. go/types records
			// best-effort type info for whatever DID resolve (e.g. the
			// receiver expression of a call whose method doesn't exist), and
			// that's all decomposeSetter needs — so still attempt the
			// rewrite; only report the errors for visibility.
			for _, e := range pkg.Errors {
				fmt.Fprintf(os.Stderr, "handlerewrite: package %s: %v\n", pkg.PkgPath, e)
			}
		}
		for i, file := range pkg.Syntax {
			if i >= len(pkg.CompiledGoFiles) {
				continue
			}
			filename := pkg.CompiledGoFiles[i]
			if seen[filename] {
				continue
			}
			seen[filename] = true
			if !RewriteChainsFile(pkg.Fset, pkg.TypesInfo, file, filename, manifest, prefixes) {
				continue
			}
			var buf bytes.Buffer
			if err := format.Node(&buf, pkg.Fset, file); err != nil {
				fmt.Fprintf(os.Stderr, "handlerewrite: format %s: %v\n", filename, err)
				continue
			}
			out, err := format.Source(buf.Bytes())
			if err != nil {
				fmt.Fprintf(os.Stderr, "handlerewrite: gofmt %s: %v\n", filename, err)
				continue
			}
			if err := os.WriteFile(filename, out, 0o644); err != nil {
				return changedFiles, err
			}
			changedFiles = append(changedFiles, filename)
		}
	}
	return changedFiles, nil
}
